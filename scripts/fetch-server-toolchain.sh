#!/usr/bin/env bash
# Fetch the server-side scripting toolchain.
#
# Downloads AMX Mod X (Pawn compiler + scripting includes) and ReAPI (its
# includes), verifies every SHA-256 against versions.lock.json and unpacks them
# under .cache/toolchain/. The cache is ignored by git.
#
# Prints shell assignments on stdout, so callers can eval the result:
#
#   eval "$(scripts/fetch-server-toolchain.sh)"
#   "$AMXXPC" plugin.sma -i"$PAWN_INCLUDE_DIR"
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT" || exit 1

# shellcheck source=scripts/lib/fetch.sh
. "$ROOT/scripts/lib/fetch.sh"

TOOLCHAIN="$CACHE/toolchain"

note() { printf '==> %s\n' "$*" >&2; }

extract_tar() {
    local key="$1" archive="$2" version dest
    version="$(lock_value server_toolchain "$key" version)"
    dest="$TOOLCHAIN/$key-$version"
    if [[ ! -d "$dest" ]]; then
        note "$key: extracting to $dest"
        mkdir -p "$dest"
        tar xzf "$archive" -C "$dest"
    fi
    printf '%s\n' "$dest"
}

extract_zip() {
    local key="$1" archive="$2" version dest
    version="$(lock_value server_toolchain "$key" version)"
    dest="$TOOLCHAIN/$key-$version"
    if [[ ! -d "$dest" ]]; then
        note "$key: extracting to $dest"
        mkdir -p "$dest"
        unzip -q "$archive" -d "$dest"
    fi
    printf '%s\n' "$dest"
}

amxx_archive="$(fetch_archive server_toolchain amxmodx)"
reapi_archive="$(fetch_archive server_toolchain reapi)"

amxx_dir="$(extract_tar amxmodx "$amxx_archive")"
reapi_dir="$(extract_zip reapi "$reapi_archive")"

amxxpc="$amxx_dir/addons/amxmodx/scripting/amxxpc"
amxx_include="$amxx_dir/addons/amxmodx/scripting/include"
reapi_include="$reapi_dir/addons/amxmodx/scripting/include"

if [[ ! -x "$amxxpc" ]]; then
    printf 'ERROR: Pawn compiler not found at %s\n' "$amxxpc" >&2
    exit 1
fi

# The Pawn verification target takes a single include directory, so merge the
# AMXX and ReAPI includes into one directory of symlinks.
merged="$TOOLCHAIN/include"
mkdir -p "$merged"
for dir in "$amxx_include" "$reapi_include"; do
    for inc in "$dir"/*.inc; do
        [[ -e "$inc" ]] || continue
        ln -sfn "$inc" "$merged/$(basename "$inc")"
    done
done

# amxxpc dlopen()s amxxpc32.so by name, so it only works when its own directory
# is on the library path. The wrapper keeps that detail out of the CMake call.
wrapper="$TOOLCHAIN/bin/amxxpc"
mkdir -p "$TOOLCHAIN/bin"
cat >"$wrapper" <<EOF
#!/usr/bin/env bash
# Generated by scripts/fetch-server-toolchain.sh. Do not edit.
exec env LD_LIBRARY_PATH="\${LD_LIBRARY_PATH:+\$LD_LIBRARY_PATH:}$(dirname "$amxxpc")" "$amxxpc" "\$@"
EOF
chmod +x "$wrapper"

printf 'AMXX_DIR=%q\n' "$amxx_dir"
printf 'REAPI_DIR=%q\n' "$reapi_dir"
printf 'AMXXPC=%q\n' "$wrapper"
printf 'PAWN_INCLUDE_DIR=%q\n' "$merged"
